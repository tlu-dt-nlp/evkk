    '  ] : [];\n'
    '\n'
    '  return (\n'
    '    <div>\n'
    '      <Box className="sv2-drawer-header">\n'
    '        <Typography variant="overline" display="block" sx={{ color: \'#4a148c\', lineHeight: 1.5 }}>\n'
    '          Filtrid\n'
    '        </Typography>\n'
    '      </Box>\n'
    '      <Divider />\n'
    '\n'
    '      <List dense disablePadding>\n'
    '        {FILTER_SECTIONS.map(({ key, label }) => {\n'
    '          const selected = filters[key];\n'
    '          const count = selected?.size || 0;\n'
    '          const isOpen = openSections.has(key);\n'
    '          const options = sectionOptions[key] || [];\n'
    '\n'
    '          return (\n'
    '            <div key={key}>\n'
    '              <ListItem disablePadding>\n'
    '                <ListItemButton onClick={() => toggleSection(key)}>\n'
    '                  <ListItemText\n'
    '                    primary={\n'
    '                      <Box sx={{ display: \'flex\', alignItems: \'center\', gap: 0.75 }}>\n'
    '                        <span>{label}</span>\n'
    '                        {count > 0 && <span className="sv2-filter-badge">{count}</span>}\n'
    '                      </Box>\n'
    '                    }\n'
    '                  />\n'
    '                  {isOpen ? <ExpandLess fontSize="small" /> : <ExpandMore fontSize="small" />}\n'
    '                </ListItemButton>\n'
    '              </ListItem>\n'
    '              <Collapse in={isOpen} timeout="auto" unmountOnExit>\n'
    '                <List dense disablePadding>\n'
