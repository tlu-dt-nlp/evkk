    '                    const isSelected = selected?.has(id);\n'
    '                    return (\n'
    '                      <ListItemButton\n'
    '                        key={id} selected={isSelected}\n'
    '                        onClick={() => toggleFilter(key, id)}\n'
    '                        sx={{ pl: 1.5 }}\n'
    '                      >\n'
    '                        <ListItemIcon sx={{ minWidth: 32 }}>\n'
    '                          <Check\n'
    '                            fontSize="small"\n'
    '                            sx={{ color: \'#9c27b0\', opacity: isSelected ? 1 : 0, fontSize: 16, transition: \'opacity 0.15s\' }}\n'
    '                          />\n'
    '                        </ListItemIcon>\n'
    '                        <ListItemText primary={id} />\n'
    '                      </ListItemButton>\n'
    '                    );\n'
