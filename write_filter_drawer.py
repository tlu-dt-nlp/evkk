    '          isOpen={openSections.has(key)}\n'
    '          onToggle={() => toggleSection(key)}\n'
    '        />\n'
    '      ))}\n'
    '\n'
    '      <Box className="sv2-drawer-footer" sx={{ display: \'flex\', flexDirection: \'column\', gap: 0.5 }}>\n'
    '        <Button\n'
