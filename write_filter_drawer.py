    '      label: \'Lausete arv\',\n'
    '      range: dataRanges.sentenceCount,\n'
    '      value: sentenceCountRange ?? dataRanges.sentenceCount,\n'
    '      onChange: setSentenceCountRange,\n'
    '      onReset: () => setSentenceCountRange(null),\n'
    '      isActive: !!(sentenceCountRange && (sentenceCountRange[0] > dataRanges.sentenceCount[0] || sentenceCountRange[1] < dataRanges.sentenceCount[1]))\n'
